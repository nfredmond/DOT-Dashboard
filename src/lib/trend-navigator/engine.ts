  /**
   * Saves a new trend definition to the database.
   * @param definitionData The trend definition data to save (without id, createdAt, updatedAt).
   * @returns The saved trend definition data (including DB-generated id).
   */
  public async saveTrendDefinition(
    definitionData: Omit<TrendDefinition, 'id' | 'createdAt' | 'updatedAt'>
  ): Promise<TrendDefinition> {
    const supabase = createClient();
    // Ensure all required new fields have defaults if not provided, or are explicitly part of definitionData
    const completeDefinitionData = {
      ...definitionData,
      inputType: definitionData.inputType || 'slider',
      predictionYears: definitionData.predictionYears || [2025, 2030, 2035], // Example default
      options: definitionData.inputType === 'select' ? definitionData.options || [] : undefined,
    };

    const { data, error } = await supabase
      .from('trend_definitions')
      .insert(completeDefinitionData as any) // Cast to any to match Supabase insert type expectation
      .select()
      .single();

    if (error) {
      console.error("Error saving trend definition:", error);
      throw error;
    }
    if (!data) {
      throw new Error("Trend definition data not returned after save.");
    }
    return data as unknown as TrendDefinition; // Double cast
  }

  /**
   * Updates an existing trend definition in the database.
   * @param id The ID of the trend definition to update.
   * @param updates Partial data containing the fields to update.
   * @returns The updated trend definition data.
   */
  public async updateTrendDefinition(
    id: string,
    updates: Partial<Omit<TrendDefinition, 'id' | 'createdAt' | 'updatedAt'>>
  ): Promise<TrendDefinition> {
    const supabase = createClient();
    // If inputType is changed from 'select' to 'slider', we might want to nullify 'options'
    const fullUpdates = { ...updates };
    if (updates.inputType === 'slider' && updates.options) {
      fullUpdates.options = undefined;  // Or null, depending on DB preference
    }


    const { data, error } = await supabase
      .from('trend_definitions')
      .update(fullUpdates as any) // Cast to any for Supabase update
      .eq('id', id)
      .select()
      .single();

    if (error) {
      console.error(`Error updating trend definition ${id}:`, error);
      throw error;
    }
    if (!data) {
      throw new Error("Trend definition data not returned after update.");
    }
    return data as unknown as TrendDefinition;
  }

  /**
   * Deletes a trend definition from the database.
   * @param id The ID of the trend definition to delete.
   */
  public async deleteTrendDefinition(id: string): Promise<void> {
    const supabase = createClient();
    const { error } = await supabase
      .from('trend_definitions')
      .delete()
      .eq('id', id);

    if (error) {
      console.error(`Error deleting trend definition ${id}:`, error);
      throw error;
    }
  }
